for (v = 1:nDepVars)
   if (CurrentY(v) < VARMIN(v+1))
      CurrentY(v) = VARMIN(v+1);
   elseif (CurrentY(v) > VARMAX(v+1))
      CurrentY(v) = VARMAX(v+1);
   end
end

